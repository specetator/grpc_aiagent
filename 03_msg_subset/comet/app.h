// ============================================================================
// comet 服务入口封装
// 
// comet 是即时通讯系统的长连接接入层，负责：
// 1. 接受客户端的 WebSocket 连接
// 2. 在握手阶段向 logic 服务验证客户端的 token
// 3. 管理在线用户的 WebSocket 连接（后续可扩展消息推送）
// 
// 架构设计：
// - 使用 muduo 网络库的事件驱动模型，支持高并发连接
// - 采用多线程 IO 模式，充分利用多核 CPU
// - 通过 gRPC 与 logic 服务通信，完成 token 验证
// 
// 使用方式：
// - 在 main 函数中调用 RunComet，传入配置对象
// - 函数会阻塞运行直到进程退出
// ============================================================================
#pragma once

#include "config.h"

namespace sparkpush {

// comet 进程主入口函数
// 
// @param cfg: 配置对象，包含监听端口、IO 线程数、logic 服务地址等
// 
// 功能：
// 1. 创建 muduo EventLoop 事件循环
// 2. 初始化 CometServer（WebSocket 服务器）
// 3. 启动多线程 IO 模型
// 4. 进入事件循环，处理连接和消息（阻塞）
// 
// 注意：
// - 该函数会阻塞当前线程，直到事件循环退出
// - 不使用全局单例，便于测试和多实例部署
void RunComet(const Config& cfg);

}  // namespace sparkpush



