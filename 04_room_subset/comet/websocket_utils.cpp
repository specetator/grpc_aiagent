// ============================================================================
// WebSocket 帧构造工具实现
//
// 本文件实现 WebSocket 协议的帧构造和消息解析功能，主要包括：
// 1. BuildWebSocketTextFrame: 构造符合 RFC 6455 规范的文本帧
// 2. ParseSingleChatJson: 轻量级解析单聊消息中的目标用户 ID
// 3. ParseChatroomJson: 轻量级解析群聊/房间消息中的房间 ID
// 4. ParseUpstreamMessage: 完整解析客户端上行消息的元信息
//
// 设计说明：
// - 服务端发送的帧不需要掩码（MASK=0），这是 WebSocket 协议的要求
// - 客户端发送的帧必须有掩码（MASK=1），在 comet_server.cpp 中处理
// - 轻量解析函数避免了完整 JSON 解析的开销，适合高频调用场景
// ============================================================================
#include "websocket_utils.h"

#include <cctype>
#include <nlohmann/json.hpp>

#include "logging.h"

namespace sparkpush {

// ============================================================================
// 函数：BuildWebSocketTextFrame
// 功能：构造 WebSocket 文本帧（服务端向客户端发送）
//
// 参数：
// @param payload: 消息内容（UTF-8 文本字符串）
//
// 返回：
// @return: 完整的 WebSocket 帧（包含帧头和负载数据）
//
// 实现说明：
// 按照 RFC 6455 规范组装帧头和负载数据，帧格式如下：
//   字节 0: FIN(1bit) + RSV(3bit) + Opcode(4bit)
//   字节 1: MASK(1bit) + Payload Length(7bit)
//   字节 2-N: 扩展长度字段（可选，取决于负载大小）
//   字节 N+1-end: 负载数据
// ============================================================================
std::string BuildWebSocketTextFrame(const std::string& payload) {
    // 用于存储最终的帧数据（帧头 + 负载）
    std::string frame;

    // ========================================================================
    // 第 1 字节：组装帧头的第一个字节
    // ========================================================================
    // 位结构（从高到低）：
    //   FIN (1 bit):  1 = 完整消息，不分片（0 表示后续还有分片）
    //   RSV1-3 (3 bits): 保留位，必须为 0（除非协商了 WebSocket 扩展）
    //   Opcode (4 bits): 帧类型，0x1 表示文本帧
    //
    // 0x81 的二进制表示: 10000001
    //   第 7 位 (FIN) = 1:  表示这是完整的单帧消息
    //   第 4-6 位 (RSV) = 000: 未使用扩展
    //   第 0-3 位 (Opcode) = 0001: 文本帧类型
    unsigned char b1 = 0x81;  // 0x81 = 10000001（二进制）
    frame.push_back(static_cast<char>(b1));

    // ========================================================================
    // 第 2 字节及后续：组装 MASK 标志位和负载长度
    // ========================================================================
    // MASK (1 bit):
    //   0 = 服务端发送，不需要掩码（RFC 6455 规定）
    //   1 = 客户端发送，必须掩码（安全考虑）
    //
    // Payload Length (7 bits 或更多):
    //   0-125: 直接用 7 位表示实际长度
    //   126: 表示实际长度用接下来的 2 字节（16位）表示
    //   127: 表示实际长度用接下来的 8 字节（64位）表示
    size_t len = payload.size();

    // ------------------------------------------------------------------------
    // 情况 1: 短消息（负载长度 < 126 字节）
    // ------------------------------------------------------------------------
    // 长度可以直接用 7 位表示，不需要额外的扩展长度字段
    if (len < 126) {
        // 第 2 字节 = MASK(0) + Length(len)
        // 由于 MASK=0（服务端），所以直接写入长度值
        frame.push_back(static_cast<char>(len));
    }
    // ------------------------------------------------------------------------
    // 情况 2: 中等消息（126 <= 负载长度 <= 65535 字节）
    // ------------------------------------------------------------------------
    // 7 位不够用，使用 16 位（2 字节）扩展长度字段
    else if (len <= 0xFFFF) {
        // 第 2 字节 = MASK(0) + 特殊值 126（表示长度在后面 2 字节）
        frame.push_back(126);
        // 接下来 2 字节：以网络字节序（大端序）存储实际长度
        frame.push_back(static_cast<char>((len >> 8) & 0xFF));  // 高 8 位
        frame.push_back(static_cast<char>(len & 0xFF));         // 低 8 位
    }
    // ------------------------------------------------------------------------
    // 情况 3: 长消息（负载长度 > 65535 字节）
    // ------------------------------------------------------------------------
    // 需要使用 64 位（8 字节）扩展长度字段
    else {
        // 第 2 字节 = MASK(0) + 特殊值 127（表示长度在后面 8 字节）
        frame.push_back(127);
        // 接下来 8 字节：以网络字节序（大端序）存储实际长度
        // 从高字节到低字节逐个写入（i 从 7 递减到 0）
        for (int i = 7; i >= 0; --i) {
            frame.push_back(static_cast<char>((len >> (8 * i)) & 0xFF));
        }
    }

    // ========================================================================
    // 追加负载数据
    // ========================================================================
    // 服务端发送的帧不需要掩码处理（MASK=0），直接追加原始负载数据
    // 注意：客户端发送的帧必须掩码（MASK=1），需要对负载进行 XOR 变换
    frame.append(payload);

    // 返回完整的 WebSocket 帧（可直接通过 TCP 连接发送）
    return frame;
}

// ============================================================================
// 函数：ParseUpstreamMessage
// 功能：解析客户端上行消息，提取关键元信息（完整 JSON 解析）
//
// 参数：
// @param json_str: 完整的 JSON 消息字符串
// @param meta: 输出参数，用于返回解析出的消息元信息
//
// 返回：
// @return: 解析成功且必填字段齐全返回 true，否则返回 false
//
// 设计说明：
// - 使用 nlohmann::json 进行完整的 JSON 解析（比轻量解析更健壮）
// - 最终协议：不做字段名兼容（只接受 target_id）
// - 校验必填字段：msg_type、target_type、target_id
// - 解析失败不抛异常，而是返回 false（避免影响 IO 线程）
//
// 消息格式示例：
// {
//   "msg_type": "text",              // 必填：消息类型
//   "target_type": "single_chat",    // 必填：目标类型（单聊/群聊）
//   "target_id": 12345,              // 必填：目标 ID（用户 ID 或房间 ID）
//   "client_msg_id": "uuid-...",     // 可选：客户端消息 ID（幂等）
//   // 最终协议：不再接收客户端时间戳（timestamp/client_timestamp_ms）
// }
// ============================================================================
bool ParseUpstreamMessage(const std::string& json_str,
                          UpstreamMessageMeta* meta) {
    // 参数校验：输出指针不能为空
    if (!meta) return false;

    // ========================================================================
    // 步骤 1: 解析 JSON 字符串
    // ========================================================================
    // 使用 nlohmann::json::parse 进行解析：
    // - 第一个参数：输入的 JSON 字符串
    // - 第二个参数：回调函数（nullptr 表示不使用）
    // - 第三个参数：false 表示解析失败时不抛异常，而是返回 discarded 对象
    //   这样可以避免异常穿透到 muduo 的 IO 线程，导致整个服务崩溃
    auto j = nlohmann::json::parse(json_str, nullptr, false);

    // 检查解析结果：
    // - is_discarded(): 解析失败时返回 true
    // - is_object(): 检查 JSON 根节点是否为对象（而非数组、字符串等）
    if (j.is_discarded() || !j.is_object()) {
        LOG_ERROR << "ParseUpstreamMessage FAILED: invalid json";
        return false;
    }

    // ========================================================================
    // 特殊处理：web_demo 心跳 ping（模拟）
    // ========================================================================
    // web 端会周期性发送：
    //   {"type":"ping","ts":1766149817947}
    // 该格式不包含 msg_type/target_type/target_id，若按业务消息解析会报
    // missing required fields。
    //
    // 这里将其识别为“控制消息”，由上层（comet_server.cpp）短路回 pong：
    //   {"type":"pong","ts":1766149817947}
    //
    // 注意：为了保持 ParseUpstreamMessage 的签名不变，这里仍返回 true，
    // 并把 msg_type/target_type 填为约定值，供上层识别。
    if (j.contains("type") && j["type"].is_string() && j["type"] == "ping") {
        UpstreamMessageMeta m;
        m.msg_type = "ping";
        m.target_type = "control";
        // 占位 target_id（避免上层把它当作解析失败）；真正业务不会使用
        m.target_id = 1;
        if (j.contains("ts") && j["ts"].is_number_integer()) {
            m.client_ts_ms = j["ts"].get<int64_t>();
        }
        *meta = m;
        return true;
    }
    LOG_INFO << "json: " << json_str;
    // ========================================================================
    // 步骤 2: 提取基础字段
    // ========================================================================
    UpstreamMessageMeta m;

    // msg_type: 消息类型（如 "text", "image", "file" 等）
    m.msg_type = j.value("msg_type", "");

    // target_type: 目标类型（如 "single_chat", "room" 等）
    m.target_type = j.value("target_type", "");

    // ========================================================================
    // 步骤 3: 提取目标 ID（最终协议：只允许 target_id）
    // ========================================================================

    // 标准字段 target_id（必填）
    if (j.contains("target_id") && j["target_id"].is_number_integer()) {
        m.target_id = j["target_id"].get<int64_t>();
    }

    // ========================================================================
    // 步骤 4: 提取可选字段
    // ========================================================================

    // client_msg_id: 客户端生成的消息唯一 ID（用于幂等、重试、对账）
    m.client_msg_id = j.value("client_msg_id", "");

    // 最终协议：不再接收客户端时间戳字段（timestamp/client_timestamp_ms）

    // ========================================================================
    // 步骤 5: 校验必填字段
    // ========================================================================
    // 必填字段：msg_type、target_type、target_id
    // 任一缺失或无效，认为不是合法的上行消息
    if (m.msg_type.empty() || m.target_type.empty() || m.target_id <= 0) {
        LOG_ERROR << "ParseUpstreamMessage FAILED: missing required fields";
        return false;
    }

    // ========================================================================
    // 步骤 6: 返回解析结果
    // ========================================================================
    *meta = m;
    return true;
}

}  // namespace sparkpush
